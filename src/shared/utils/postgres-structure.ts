import type { PostgresColumnDefinition, PostgresStructureChange } from '../types/database'
import { quotePostgresIdentifier as quote, quotePostgresValue as literal } from './postgres-preview'

export const postgresColumnTypes = [
  'text', 'varchar', 'smallint', 'integer', 'bigint', 'numeric', 'real', 'double precision',
  'boolean', 'date', 'time', 'timestamp', 'timestamptz', 'interval', 'uuid', 'json', 'jsonb', 'bytea'
]

function identifier(value: unknown): string {
  if (typeof value !== 'string' || !value.trim() || value.includes('\0') || new TextEncoder().encode(value).length > 63) {
    throw new Error('Tên schema, bảng hoặc cột phải dài từ 1 đến 63 byte.')
  }
  return quote(value)
}

function typeSql(value: unknown): string {
  if (typeof value === 'string' && (postgresColumnTypes.includes(value) || /^(?:varchar\([1-9]\d{0,6}\)|numeric\([1-9]\d{0,3}(?:,[+-]?\d{1,4})?\))$/.test(value))) return value
  throw new Error('Kiểu cột chưa hỗ trợ trong form. Hãy dùng kiểu PostgreSQL có trong danh sách hoặc chạy SQL riêng.')
}

function valueSql(value: unknown): string {
  if (typeof value !== 'string' || value.includes('\0') || value.length > 10_000) throw new Error('Giá trị hoặc ghi chú không hợp lệ.')
  return literal(value)
}

function columnSql(column: PostgresColumnDefinition): string {
  if (!column || typeof column !== 'object') throw new Error('Thông tin cột không hợp lệ.')
  const type = typeSql(column.type)
  const clauses = [identifier(column.name), type]
  if (column.identity === true) {
    if (!['smallint', 'integer', 'bigint'].includes(type) || column.defaultValue !== undefined) {
      throw new Error('IDENTITY cần kiểu số nguyên và không dùng giá trị mặc định riêng.')
    }
    clauses.push('GENERATED BY DEFAULT AS IDENTITY')
  }
  if (column.defaultValue !== undefined) clauses.push(`DEFAULT ${valueSql(column.defaultValue)}`)
  if (column.notNull === true) clauses.push('NOT NULL')
  if (column.unique === true) clauses.push('UNIQUE')
  return clauses.join(' ')
}

export function postgresStructureSql(input: unknown): string[] {
  if (!input || typeof input !== 'object') throw new Error('Thay đổi cấu trúc không hợp lệ.')
  const change = input as PostgresStructureChange
  const target = `${identifier(change.schema)}.${identifier(change.table)}`
  const alter = `ALTER TABLE ${target}`
  switch (change.op) {
    case 'create-table': {
      if (!Array.isArray(change.columns) || !change.columns.length || change.columns.length > 1600) throw new Error('Hãy khai báo các cột cho bảng.')
      const columns = change.columns.map(columnSql)
      if (new Set(change.columns.map((column) => column.name)).size !== columns.length) throw new Error('Tên cột bị trùng.')
      const keys = change.columns.filter((column) => column.primaryKey === true).map((column) => identifier(column.name))
      if (keys.length) columns.push(`PRIMARY KEY (${keys.join(', ')})`)
      return [`CREATE TABLE ${target} (\n  ${columns.join(',\n  ')}\n);`]
    }
    case 'edit-table': {
      const name = identifier(change.name)
      const newSchema = identifier(change.newSchema)
      const renamed = `${identifier(change.schema)}.${name}`
      const statements: string[] = []
      if (change.name !== change.table) statements.push(`${alter} RENAME TO ${name};`)
      if (change.newSchema !== change.schema) statements.push(`ALTER TABLE ${renamed} SET SCHEMA ${newSchema};`)
      if (change.comment !== undefined) statements.push(`COMMENT ON TABLE ${newSchema}.${name} IS ${change.comment ? valueSql(change.comment) : 'NULL'};`)
      return statements
    }
    case 'drop-table':
      return [`DROP TABLE ${target} RESTRICT;`]
    case 'add-column':
      return [`${alter} ADD COLUMN ${columnSql(change.definition)}${change.definition.primaryKey === true ? ' PRIMARY KEY' : ''};`]
    case 'edit-column': {
      const column = identifier(change.column)
      const name = identifier(change.name)
      const prefix = `${alter} ALTER COLUMN ${name}`
      const statements: string[] = []
      if (change.column !== change.name) statements.push(`${alter} RENAME COLUMN ${column} TO ${name};`)
      if (change.defaultValue !== undefined && (change.defaultValue === null || change.type !== undefined)) statements.push(`${prefix} DROP DEFAULT;`)
      if (change.type !== undefined) statements.push(`${prefix} TYPE ${typeSql(change.type)};`)
      if (change.defaultValue !== undefined && change.defaultValue !== null) statements.push(`${prefix} SET DEFAULT ${valueSql(change.defaultValue)};`)
      if (typeof change.notNull === 'boolean') statements.push(`${prefix} ${change.notNull ? 'SET' : 'DROP'} NOT NULL;`)
      return statements
    }
    case 'drop-column':
      return [`${alter} DROP COLUMN ${identifier(change.column)} RESTRICT;`]
    default:
      throw new Error('Thay đổi cấu trúc không được hỗ trợ.')
  }
}
